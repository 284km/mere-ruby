#!/usr/bin/env python3
"""Write the import library of an interpreter's C API.

    import_library.py <mere-ruby executable> <output directory> [--cc clang]

The C API is in the executable: an extension links against nothing and finds
`rb_*` in the process that loads it. A test PROGRAM has nothing to link
against, and mkmf's `have_func("rb_enc_interned_str")` is exactly that -- a
program that names the function is linked, and the answer is whether it
linked. With no library the answer was "no" for every ruby function, the ones
that are there included, and an extension then compiles its own substitute.

This writes libmere-ruby-api (.dylib / .so): one symbol for each function and
variable of the C API that the executable exports, and nothing behind them.
RbConfig names it as LIBRUBYARG, which mkmf puts on the link line of its test
programs only; an extension's own link line does not have it. Linking against
it answers "is this function in this interpreter" and nothing else: a program
linked with it cannot call the functions (each stub aborts, saying so).

Left out, so that the answer for them is "no" and an extension takes its
other path: the functions of capi/unsupported.c, which exist only to raise
NotImplementedError.
"""
from pathlib import Path
import argparse
import re
import subprocess
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
parser.add_argument('executable', type=Path)
parser.add_argument('output', type=Path)
parser.add_argument('--cc', default='clang')
args = parser.parse_args()
darwin = sys.platform == 'darwin'
unsupported = set(re.findall(r'UNSUPPORTED\((\w+)\)', (HERE.parent / 'unsupported.c').read_text())) - {'name'}
listing = subprocess.check_output(['nm', '-g', '--defined-only', str(args.executable)] if not darwin
                                  else ['nm', '-gU', str(args.executable)], text=True)
functions, variables = [], []
for line in listing.splitlines():
    parts = line.split()
    if len(parts) != 3:
        continue
    kind, name = parts[1], parts[2]
    if darwin:
        if not name.startswith('_'):
            continue
        name = name[1:]
    if not re.match(r'(rb_|ruby_|st_|onig)', name) or name.startswith('rb_mere_') or name in unsupported:
        continue
    (functions if kind in 'Tt' else variables).append(name)
if len(functions) < 500:
    sys.exit(f'import_library: only {len(functions)} C API functions found in {args.executable}')
args.output.mkdir(parents=True, exist_ok=True)
source = args.output / 'mere_ruby_api.c'
lines = ['/* Generated by capi/tools/import_library.py: the names of the C API, for a',
         ' * linker to find. Nothing here does anything. */',
         '#include <stdio.h>', '#include <stdlib.h>',
         'static void only_names(const char *name) {',
         '    fprintf(stderr, "%s: libmere-ruby-api only names the C API; the functions are in the mere-ruby executable\\n", name);',
         '    abort();', '}']
lines += [f'void {name}(void) {{ only_names("{name}"); }}' for name in sorted(functions)]
lines += [f'void *{name}[4];' for name in sorted(variables)]
source.write_text('\n'.join(lines) + '\n')
# (by its full path: a test program that is RUN finds the library where it was written)
library = args.output.resolve() / ('libmere-ruby-api.dylib' if darwin else 'libmere-ruby-api.so')
name = ['-install_name', str(library)] if darwin else []
subprocess.run([args.cc, '-shared', '-fPIC', '-w', str(source), *name, '-o', str(library)], check=True)
print(f'import_library: {library.name} names {len(functions)} functions and {len(variables)} variables '
      f'({len(unsupported)} unsupported ones left out)')
