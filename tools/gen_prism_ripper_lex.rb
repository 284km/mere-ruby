# Generate the private recovery consumer from the actual reference method.
# Prism is MIT licensed; see vendor/prism/LICENSE.md.
require 'prism'
require 'rbconfig'
path = File.join(RbConfig::CONFIG.fetch('rubylibdir'), 'prism/lex_compat.rb')
tree = Prism.parse_file(path)
abort 'cannot parse reference LexCompat' unless tree.success?
methods = []
visit = lambda do |node|
  methods << node if node.is_a?(Prism::DefNode) && node.name == :result
  node.compact_child_nodes.each { |child| visit.call(child) }
end
visit.call(tree.value)
abort 'expected one LexCompat#result' unless methods.size == 1
body = methods.first.location.slice
call = 'result = Prism.lex(source, **options)'
abort 'reference LexCompat lexer call changed' unless body.scan(call).size == 1
body = body.sub(call, 'result = Prism.__ripper_lex(source, **options)')
# The method inherits its original file's literal setting as well as its Cref.
pragma = File.foreach(path).first
abort 'reference literal setting changed' unless pragma == "# frozen_string_literal: true\n"
print pragma
puts '# Generated by tools/gen_prism_ripper_lex.rb from reference Prism::LexCompat#result.'
puts '# MIT licensed reference Prism code; see vendor/prism/LICENSE.md.'
puts '# Only the native token producer differs. Public LexCompat is unchanged.'
puts 'module Prism'
puts '  class LexCompat'
puts '    class RipperRecovery < LexCompat'
# Preserve the original lexical constants and literal bytes. Adding indentation
# to every source line could change a future multiline literal in this method.
print body
puts unless body.end_with?("\n")
puts '    end'
puts '  end'
puts 'end'
