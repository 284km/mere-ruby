# Generates the double-byte tables (GBK, Big5 and its HKSCS / UAO variants)
# embedded in m_unicode.mere between the DBCS_TABLES markers; ruby's own
# transcoder is the oracle, as for gen_jis0208.rb.
#
#   ruby tools/gen_dbcs_tables.rb > /tmp/dbcs.mere   # then splice it in
#
# A grid is every lead 0x81-0xFE x trail 0x40-0xFE, 4 hex digits a slot
# ("0000": no character). A variant is its base grid plus "LLTT:CP" entries
# that differ (CP "0" removes one). The encoders build their reverse maps
# from these in order, first slot wins; "CP:LLTT" lists where ruby encodes a
# character to another slot than that.
LEADS = (0x81..0xFE).to_a
TRAILS = (0x40..0xFE).to_a
def table(enc)
  h = {}
  LEADS.each { |l| TRAILS.each { |t|
    begin
      u = [l, t].pack("C2").force_encoding(enc).encode("UTF-8")
      h[[l, t]] = u.ord if u.size == 1
    rescue Encoding::UndefinedConversionError, Encoding::InvalidByteSequenceError
    end } }
  h
end
def grid(h) = LEADS.flat_map { |l| TRAILS.map { |t| format("%04X", h[[l, t]] || 0) } }.join
def overrides(base, h)
  out = []
  h.each { |k, v| out << format("%02X%02X:%X", *k, v) if base[k] != v }
  base.each_key { |k| out << format("%02X%02X:0", *k) unless h.key?(k) }
  out.join(",")
end
def reverse_fixes(enc, h)
  first = {}
  h.sort.each { |k, v| first[v] ||= k }
  out = []
  first.each do |cp, k|
    begin
      b = [cp].pack("U").encode(enc).bytes
      out << format("%X:%02X%02X", cp, *b) if b.size == 2 && b != k
    rescue Encoding::UndefinedConversionError
      out << format("%X:0", cp)
    end
  end
  out.join(",")
end
gbk = table("GBK"); big5 = table("Big5"); hk = table("Big5-HKSCS"); uao = table("Big5-UAO")
gb2 = gbk.select { |(l, t), _| l >= 0xA1 && t >= 0xA1 }
puts "// DBCS_TABLES BEGIN (generated by tools/gen_dbcs_tables.rb)"
puts "let dbcs_gbk_grid = \"#{grid(gbk)}\";"
puts "let dbcs_big5_grid = \"#{grid(big5)}\";"
puts "let dbcs_hkscs_over = \"#{overrides(big5, hk)}\";"
puts "let dbcs_uao_over = \"#{overrides(big5, uao)}\";"
puts "let dbcs_gbk_rev = \"#{reverse_fixes("GBK", gbk)}\";"
puts "let dbcs_gb2312_rev = \"#{reverse_fixes("GB2312", gb2)}\";"
puts "let dbcs_big5_rev = \"#{reverse_fixes("Big5", big5)}\";"
puts "let dbcs_hkscs_rev = \"#{reverse_fixes("Big5-HKSCS", hk)}\";"
puts "let dbcs_uao_rev = \"#{reverse_fixes("Big5-UAO", uao)}\";"
# The JIS family's variants, as differences from the base ruby decodes and
# encodes them by (Shift_JIS for Windows-31J, EUC-JP for eucJP-ms and
# CP51932): "LLTT:CP" where the variant decodes otherwise ("0": it has no
# character there), and "CP:LLTT" where it encodes otherwise ("CP:0": it
# cannot).
def two(enc, b) = (b.force_encoding(enc).encode("UTF-8") rescue nil).then { |u| u && u.size == 1 ? u.ord : nil }
def variant(base, var, leads, trails)
  dec = []
  cps = {}
  leads.each { |l| trails.each { |t|
    b = [l, t].pack("C2")
    x = two(base, b.dup); y = two(var, b.dup)
    dec << format("%02X%02X:%X", l, t, y || 0) if x != y
    cps[x] = true if x; cps[y] = true if y } }
  enc = []
  cps.keys.sort.each do |cp|
    c = [cp].pack("U")
    eb = (c.encode(base).b rescue nil); ev = (c.encode(var).b rescue nil)
    next if eb == ev
    enc << (ev && ev.bytesize == 2 ? format("%X:%02X%02X", cp, *ev.bytes) : (ev ? nil : format("%X:0", cp)))
  end
  [dec.join(","), enc.compact.join(",")]
end
sj_leads = (0x81..0x9F).to_a + (0xE0..0xFC).to_a
sj_trails = (0x40..0x7E).to_a + (0x80..0xFC).to_a
w_d, w_e = variant("Shift_JIS", "Windows-31J", sj_leads, sj_trails)
m_d, m_e = variant("EUC-JP", "eucJP-ms", (0xA1..0xFE), (0xA1..0xFE))
c_d, c_e = variant("EUC-JP", "CP51932", (0xA1..0xFE), (0xA1..0xFE))
puts "let jisv_w31j_dec = \"#{w_d}\";"
puts "let jisv_w31j_enc = \"#{w_e}\";"
puts "let jisv_eucms_dec = \"#{m_d}\";"
puts "let jisv_eucms_enc = \"#{m_e}\";"
puts "let jisv_cp51932_dec = \"#{c_d}\";"
puts "let jisv_cp51932_enc = \"#{c_e}\";"
# EBCDIC (IBM037): all 256 bytes, ASCII is not its lower half
puts "let ebcdic037 = \"#{(0..255).map { |b| (b.chr.force_encoding("IBM037").encode("UTF-8").ord rescue -1) }.join(",")}\";"
puts "// DBCS_TABLES END"
