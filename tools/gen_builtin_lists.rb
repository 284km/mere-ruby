# Generates m_builtin_lists.mere: the PUBLIC instance methods each core class
# defines itself, as far as mere-ruby answers them -- what
# `String.public_instance_methods(false)` and the inherited lists name.
#
#   . ./tools/ref_ruby.sh
#   ruby tools/gen_builtin_lists.rb list > /tmp/bl_names.txt
#   ./mere-ruby tools/missing_names.rb probe /tmp/bl_names.txt > /tmp/bl_verdict.txt
#   ruby tools/gen_builtin_lists.rb gen /tmp/bl_names.txt /tmp/bl_verdict.txt > m_builtin_lists.mere
#
# A list is a CLAIM: every name in it says "this object answers that". The
# names come from the reference (public_instance_methods(false), so nothing
# here is invented), and a name mere-ruby does not answer -- missing_names.rb
# calls each one, directly and through __send__, and reports the ones that
# are undefined both ways (ABSENT) -- is left out. Regenerate after
# implementing names, or the lists under-claim; the table records the two
# versions it was made from.
#
# Kernel, BasicObject and Comparable are not here: collect_vis answers those
# from kernel_instance_list and its two short lists (note 431).
CLASSES = %w[String Array Hash Integer Float Symbol Range NilClass TrueClass FalseClass
             Rational Complex Proc Method UnboundMethod Regexp MatchData Time Struct
             Exception Enumerator Numeric Enumerable Encoding Random].freeze

mode = ARGV[0]
case mode
when "list"
  CLASSES.each do |cn|
    Object.const_get(cn).public_instance_methods(false).map(&:to_s).sort.each { |m| puts "#{cn}##{m}" }
  end
when "gen"
  names = File.readlines(ARGV[1], chomp: true)
  absent = Hash.new { |h, k| h[k] = [] }
  section = nil
  File.readlines(ARGV[2], chomp: true).each do |l|
    section = l[/\A(ABSENT|SEND-ONLY):/, 1] || section
    next unless section == "ABSENT" && (m = l.match(/\A  (\S+) \(\d+\): (.*)\z/))
    absent[m[1]].concat(m[2].split(" "))
  end
  by_cls = Hash.new { |h, k| h[k] = [] }
  names.each do |l|
    cn, m = l.split("#", 2)
    by_cls[cn] << m unless absent[cn].include?(m)
  end
  puts "// GENERATED by tools/gen_builtin_lists.rb -- do not edit."
  puts "// The public instance methods each core class defines itself, from"
  puts "// ruby #{RUBY_VERSION}'s public_instance_methods(false), less what mere-ruby"
  puts "// did not answer when this was made (missing_names.rb's ABSENT). Read by"
  puts "// collect_vis for the reflection lists and by respond_to?."
  puts ""
  puts "let builtin_own_names = fn (cls: str) ->"
  CLASSES.each_with_index do |cn, i|
    list = by_cls[cn].join(" ")
    puts "  #{i == 0 ? "if" : "else if"} str_eq cls \"#{cn}\" then \"#{list.gsub("\\", "\\\\\\\\").gsub('"', '\\"')}\""
  end
  puts "  else \"\";"
  total = names.size
  kept = by_cls.values.sum(&:size)
  warn "kept #{kept} of #{total} names"
end
