# Generates m_delegate_lib.mere: ruby's own delegate.rb, turned into Mere
# string literals so that `require "delegate"` needs no stdlib on the load
# path.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_delegate_lib.rb > m_delegate_lib.mere
#
# The file is the reference's lib/delegate.rb (the delegate gem, BSD-2-Clause
# or Ruby's license), byte for byte. mere-ruby shipped an approximation of
# its own before: forwarding through method_missing instead of the methods
# DelegateClass defines, which reflection, cloning and freezing could tell
# apart. The real file needs `::Kernel.dup` to be a copy (note 434).
require "rbconfig"
dir = ARGV[0] || RbConfig::CONFIG["rubylibdir"]
src = File.read("#{dir}/delegate.rb")
version = src[/VERSION = "([^"]+)"/, 1]

def lit(line)
  line.gsub(/[\\"{}\t\r]/) { |c| { "\\" => "\\\\", '"' => '\\"', "{" => "\\{", "}" => "\\}", "\t" => "\\t", "\r" => "\\r" }[c] }
end

puts "// GENERATED by tools/gen_delegate_lib.rb from delegate #{version}'s"
puts "// lib/delegate.rb -- do not edit. Answered by delegate_lib_src, which"
puts "// do_require asks after syslog_lib_src."
puts ""
puts "let delegate_lib_src = fn (name: str) ->"
puts "  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in"
puts "  if str_eq n \"delegate\" then"
lines = src.lines
lines.each_with_index do |l, j|
  nl = l.end_with?("\n") ? "\\n" : ""
  puts "    \"#{lit(l.chomp)}#{nl}\"#{j == lines.size - 1 ? "" : " ++"}"
end
puts "  else \"\";"
