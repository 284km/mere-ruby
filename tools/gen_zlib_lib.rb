# Embed the Zlib Ruby API without requiring a file on the guest load path.
# ruby tools/gen_zlib_lib.rb > m_zlib_lib.mere
source = %w[zlib_ext.rb zlib_stream.rb zlib_gzip.rb].map { |name| File.read(File.expand_path("../lib/#{name}", __dir__)) }.join("\n")
puts '// GENERATED by tools/gen_zlib_lib.rb from lib/zlib_{ext,stream,gzip}.rb; do not edit.'
puts 'let zlib_lib_src = fn (u: unit) ->'
lines = source.lines
lines.each_with_index do |line, i|
  body = line.chomp.gsub(/[\\"{}\t\r]/) do |c|
    {"\\" => "\\\\", '"' => '\\"', '{' => '\\{', '}' => '\\}', "\t" => '\\t', "\r" => '\\r'}[c]
  end
  puts "  \"#{body}#{line.end_with?("\n") ? '\\n' : ''}\"#{i + 1 == lines.size ? ';' : ' ++'}"
end
