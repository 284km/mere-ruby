# Generate embedded, per-feature Ruby source from the pinned vendor tree.
# ruby tools/gen_network_lib.rb > m_network_lib.mere
require 'json'
require 'digest'
root = File.expand_path('..', __dir__)
manifest = JSON.parse(File.read(File.join(root, 'vendor/network/PROVENANCE.json')))
files = manifest.fetch('files_sha256').keys.sort

def literal(line)
  line.gsub(/[\\"{}\t\r]/) { |c| {"\\"=>"\\\\", '"'=>'\\"', '{'=>'\\{', '}'=>'\\}', "\t"=>'\\t', "\r"=>'\\r'}.fetch(c) }
end
puts '// GENERATED by tools/gen_network_lib.rb; source and licenses in vendor/network.'
puts 'let network_timeout_unavailable = fn (u: unit) ->'
adapter = <<~'RUBY'
  module Timeout
    def self.timeout(sec, klass = nil, message = nil)
      return yield(sec) if sec.nil? || sec.zero?
      raise NotImplementedError, 'asynchronous Timeout is unavailable on this target'
    end
  end
RUBY
adapter.lines.each_with_index do |line, index|
  puts '  "' + literal(line.chomp) + '\n"' + (index+1==adapter.lines.size ? ';' : ' ++')
end
files.each_with_index do |file, index|
  bytes = File.binread(File.join(root, 'vendor/network/lib', file))
  abort "network source digest changed: #{file}" unless Digest::SHA256.hexdigest(bytes) == manifest.fetch('files_sha256').fetch(file)
  source = bytes.force_encoding('UTF-8')
  puts "let network_source_#{index} = fn (u: unit) ->"
  lines = source.lines
  lines.each_with_index do |line, n|
    puts '  "' + literal(line.chomp) + (line.end_with?("\n") ? '\\n' : '') + '"' + (n+1==lines.size ? ';' : ' ++')
  end
end
puts 'let network_lib_src = fn (name: str) ->'
puts '  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in'
files.each_with_index do |file, index|
  source = 'network_source_' + index.to_s + ' ()'
  source = '(if fb_can_suspend then ' + source + ' else ' + source + ' ++ network_timeout_unavailable ())' if file=='timeout.rb'
  puts '  ' + (index==0 ? 'if ' : 'else if ') + 'str_eq n "' + file.delete_suffix('.rb') + '" then ' + source
end
puts '  else "";'
