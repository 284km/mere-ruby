# Generates m_prism_schema.mere: what each Prism node is made of, in the
# order the serialized form writes it, as one Mere string -- the table the
# builtin node loader (m_prism_load.mere) reads instead of running
# lib/prism/serialize.rb's generated Loader#load_node in Ruby.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_prism_schema.rb <ruby-src> > m_prism_schema.mere
#
# The source is <ruby-src>/prism/config.yml, the file Prism's own templates
# generate node.rb, serialize.rb and serialize.c from: a node's type number
# is its place in `nodes:` (from 1), its class is its name, and its fields
# are serialized in the order they are listed. One line a node:
#
#   CallNode receiver:N call_operator_loc:o name:c ...
#
# with one letter for how a field is written (templates/src/serialize.c.erb)
# and read (templates/lib/prism/serialize.rb.erb):
#
#   n node        N node?       L node[]
#   s string      c constant    C constant?   K constant[]
#   l location    o location?
#   b uint8       u uint32      i integer     d double
#
# A node whose name starts with `!` is written with a 4-byte length after its
# location (template.rb's needs_serialized_length?: DefNode).
#
# Like m_prism_lib.mere it is one chain of literals inside a function: a
# top-level value would nest the rest of the program one level deeper in the
# emitted C (tools/bracket_depth_check.sh).
require "yaml"

src = ARGV[0] or abort "usage: gen_prism_schema.rb <ruby-src>"
config = YAML.load_file(File.join(src, "prism", "config.yml"))
version = File.read(File.join(src, "prism", "version.h"))[/PRISM_VERSION "([^"]+)"/, 1]

KINDS = {
  "node" => "n", "node?" => "N", "node[]" => "L",
  "string" => "s", "constant" => "c", "constant?" => "C", "constant[]" => "K",
  "location" => "l", "location?" => "o",
  "uint8" => "b", "uint32" => "u", "integer" => "i", "double" => "d",
}.freeze

lines = config.fetch("nodes").map do |node|
  name = node.fetch("name")
  fields = (node["fields"] || []).map do |f|
    kind = KINDS[f.fetch("type")] or abort "gen_prism_schema: #{name}.#{f["name"]} has a type this does not know: #{f["type"]}"
    "#{f.fetch("name")}:#{kind}"
  end
  ([name == "DefNode" ? "!#{name}" : name] + fields).join(" ")
end

puts "// GENERATED by tools/gen_prism_schema.rb from prism/config.yml"
puts "// (Prism #{version}, #{lines.size} nodes) -- do not edit. Read by"
puts "// m_prism_load.mere; the letters are explained in the generator."
puts ""
puts "let prism_schema_src = fn (u: unit) ->"
lines.each_with_index do |l, i|
  puts "  #{i == 0 ? "" : "++ "}\"#{l}\\n\""
end
puts ";"
