# Generates m_prism_schema.mere: what each Prism node is made of, in the
# order the serialized form writes it, as one Mere string -- the table the
# builtin node loader (m_prism_load.mere) reads instead of running
# lib/prism/serialize.rb's generated Loader#load_node in Ruby.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_prism_schema.rb <ruby-src> > m_prism_schema.mere
#
# The source is <ruby-src>/prism/config.yml, the file Prism's own templates
# generate node.rb, serialize.rb and serialize.c from: a node's type number
# is its place in `nodes:` (from 1), its class is its name, and its fields
# are serialized in the order they are listed. One line a node:
#
#   CallNode receiver:N call_operator_loc:o name:c ...
#
# with one letter for how a field is written (templates/src/serialize.c.erb)
# and read (templates/lib/prism/serialize.rb.erb):
#
#   n node        N node?       L node[]
#   s string      c constant    C constant?   K constant[]
#   l location    o location?
#   b uint8       u uint32      i integer     d double
#
# A node whose name starts with `!` is written with a 4-byte length after its
# location (template.rb's needs_serialized_length?: DefNode).
#
# Like m_prism_lib.mere it is one chain of literals inside a function: a
# top-level value would nest the rest of the program one level deeper in the
# emitted C (tools/bracket_depth_check.sh).
#
# With `nodes` as the second argument it writes m_prism_nodes.mere instead:
# the same table as Mere functions over the decoded tree (m_prism_dec.mere,
# where a node is a run of integers in pm_nd) -- for each node type its
# number, `pm_t_call ()`; for each field a reader, `pm_call_receiver n`
# (a location is two, `pm_call_message_loc_s n` and `_e n`, the offsets it
# starts and ends at, -1 when it is absent; a double is `_hi` and `_lo`);
# for the errors the translator names, their type numbers,
# `pm_e_expect_eol_after_statement ()`;
# and `ast_tr_node`, which hands a node to the function named for its type
# (`tr_call`), the translator to parse.y's tree in m_ast.mere. They are
# functions, not values, for the reason above. Only the names the sources
# use are written (a function nobody calls is one tools/dead_defs_check.sh
# refuses): a new use of a reader needs the file generated again.
#
#   ruby tools/gen_prism_schema.rb <ruby-src> nodes > m_prism_nodes.mere
require "yaml"

src = ARGV[0] or abort "usage: gen_prism_schema.rb <ruby-src> [nodes]"
config = YAML.load_file(File.join(src, "prism", "config.yml"))
version = File.read(File.join(src, "prism", "version.h"))[/PRISM_VERSION "([^"]+)"/, 1]

KINDS = {
  "node" => "n", "node?" => "N", "node[]" => "L",
  "string" => "s", "constant" => "c", "constant?" => "C", "constant[]" => "K",
  "location" => "l", "location?" => "o",
  "uint8" => "b", "uint32" => "u", "integer" => "i", "double" => "d",
}.freeze

lines = config.fetch("nodes").map do |node|
  name = node.fetch("name")
  fields = (node["fields"] || []).map do |f|
    kind = KINDS[f.fetch("type")] or abort "gen_prism_schema: #{name}.#{f["name"]} has a type this does not know: #{f["type"]}"
    "#{f.fetch("name")}:#{kind}"
  end
  ([name == "DefNode" ? "!#{name}" : name] + fields).join(" ")
end

if ARGV[1] == "nodes"
  # (only the names the sources use are written: a reader nobody calls is a
  #  definition tools/dead_defs_check.sh refuses, and there are 500 of them.
  #  The sources are the .mere files beside this tool's directory and the
  #  standalone translator's; a new use needs the file generated again.)
  root = File.expand_path("..", __dir__)
  used = (Dir[File.join(root, "*.mere")] + Dir[File.join(root, "tools", "ast_dump", "*.mere")])
         .reject { |f| File.basename(f) == "m_prism_nodes.mere" }
         .flat_map { |f| File.read(f).gsub(%r{//.*$}, "").scan(/\bpm_[a-z0-9_]+/) }.uniq
  out = ->(line) { puts line if used.include?(line[/\Alet (pm_[a-z0-9_]+)/, 1]) }
  # (how many integers a field takes in a node's record)
  width = { "l" => 2, "o" => 2, "d" => 2 }
  snake = ->(name) { name.delete_suffix("Node").gsub(/([a-z0-9])([A-Z])/, '\\1_\\2').downcase }
  puts "// GENERATED by tools/gen_prism_schema.rb nodes from prism/config.yml"
  puts "// (Prism #{version}, #{lines.size} nodes) -- do not edit. A node of the"
  puts "// decoded tree is pm_nd[n..]: its type, the offsets it starts and ends"
  puts "// at, its flags, its node id, then its fields (m_prism_dec.mere)."
  puts ""
  config.fetch("nodes").each_with_index do |node, i|
    sn = snake.(node.fetch("name"))
    out.("let pm_t_#{sn} = fn (u: unit) -> #{i + 1};")
    at = 5
    (node["fields"] || []).each do |f|
      k = KINDS.fetch(f.fetch("type"))
      fn = f.fetch("name")
      case k
      when "l", "o"
        out.("let pm_#{sn}_#{fn}_s = fn (n: int) -> vec_get pm_nd (n + #{at});")
        out.("let pm_#{sn}_#{fn}_e = fn (n: int) -> vec_get pm_nd (n + #{at + 1});")
      when "d"
        out.("let pm_#{sn}_#{fn}_hi = fn (n: int) -> vec_get pm_nd (n + #{at});")
        out.("let pm_#{sn}_#{fn}_lo = fn (n: int) -> vec_get pm_nd (n + #{at + 1});")
      else
        out.("let pm_#{sn}_#{fn} = fn (n: int) -> vec_get pm_nd (n + #{at});")
      end
      at += width.fetch(k, 1)
    end
  end
  # (a flag set's values are bits 2 and up, in the order listed: 0 and 1 are
  #  every node's newline and static-literal flags -- templates/include/prism/ast.h.erb)
  puts ""
  out.("let pm_f_newline = fn (u: unit) -> 1;")
  out.("let pm_f_static_literal = fn (u: unit) -> 2;")
  config.fetch("flags").each do |set|
    sn = snake.(set.fetch("name").delete_suffix("Flags")).delete_suffix("_node")
    set.fetch("values").each_with_index do |v, i|
      out.("let pm_f_#{sn}_#{v.fetch("name").downcase} = fn (u: unit) -> #{1 << (i + 2)};")
    end
  end
  # (an error's type is its place in `errors:`; only the ones the translator
  #  asks about by name)
  puts ""
  %w[EXPECT_EOL_AFTER_STATEMENT].each do |name|
    i = config.fetch("errors").index(name) or abort "gen_prism_schema: config.yml has no error #{name}"
    out.("let pm_e_#{name.downcase} = fn (u: unit) -> #{i};")
  end
  puts ""
  puts "// A node to the function that translates its type."
  puts "let ast_tr_node = fn (n: int) ->"
  puts "  match vec_get pm_nd n with"
  config.fetch("nodes").each_with_index do |node, i|
    puts "  | #{i + 1} -> tr_#{snake.(node.fetch("name"))} n"
  end
  puts "  | _ -> tr_unknown n;"
  exit
end

puts "// GENERATED by tools/gen_prism_schema.rb from prism/config.yml"
puts "// (Prism #{version}, #{lines.size} nodes) -- do not edit. Read by"
puts "// m_prism_load.mere; the letters are explained in the generator."
puts ""
puts "let prism_schema_src = fn (u: unit) ->"
lines.each_with_index do |l, i|
  puts "  #{i == 0 ? "" : "++ "}\"#{l}\\n\""
end
puts ";"
