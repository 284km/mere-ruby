# Generates m_ic_schema.mere: what the native ISeq compiler (m_ic_*.mere,
# note 552) knows of Prism's nodes -- each type's number, how its fields are
# written in the serialized form, a reader for every field, and the flags.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_ic_schema.rb <ruby-src> > m_ic_schema.mere
#
# The source is <ruby-src>/prism/config.yml, the file Prism's own templates
# generate node.rb, serialize.rb and serialize.c from: a node's type number
# is its place in `nodes:` (from 1) and its fields are serialized in the
# order they are listed. For `CallNode` with the field `receiver` this writes
#
#   pt_call ()                 the type's number
#   pn_call_receiver cx n      the field's first word
#   pn_call_receiver_b cx n    its second (a list's or a location's length)
#   pq_call_safe_navigation cx n    a flag of the node's
#
# and the words of a field are, by how it is written:
#
#   n node, N node?      the node (-1: none), 0
#   L node[]             where the list starts in the list store, how many
#   l location, o loc?   the start (-1: none), the length
#   c constant, C const? the constant's number in the pool from 1 (0: none), 0
#   K constant[]         where the numbers start in the list store, how many
#   s string             its place among the strings, 0
#   b uint8, u uint32    the number, 0
#   i integer            the number and 1, or its place among the big ones and 0
#   d double             its place among the doubles, 0
#
# Everything here is a function: a top-level value would nest the rest of
# the program one level deeper in the emitted C (tools/bracket_depth_check.sh).
require "yaml"

src = ARGV[0] or abort "usage: gen_ic_schema.rb <ruby-src>"
config = YAML.load_file(File.join(src, "prism", "config.yml"))
version = File.read(File.join(src, "prism", "version.h"))[/PRISM_VERSION "([^"]+)"/, 1]

KINDS = {
  "node" => "n", "node?" => "N", "node[]" => "L",
  "string" => "s", "constant" => "c", "constant?" => "C", "constant[]" => "K",
  "location" => "l", "location?" => "o",
  "uint8" => "b", "uint32" => "u", "integer" => "i", "double" => "d",
}.freeze

snake = ->(s) { s.gsub(/([a-z0-9])([A-Z])/, '\1_\2').downcase }
short = ->(name) { snake.(name.sub(/Node\z/, "")) }
flags = config.fetch("flags").to_h { |f| [f.fetch("name"), f.fetch("values").map { |v| v.fetch("name") }] }
nodes = config.fetch("nodes")

puts "// GENERATED by tools/gen_ic_schema.rb from prism/config.yml"
puts "// (Prism #{version}, #{nodes.size} nodes) -- do not edit. What the letters and"
puts "// the names mean is in the generator."
puts ""
puts "// how a type's fields are written, a letter each (\"\" for no such type);"
puts "// `!` first: a 4-byte length follows the location"
puts "let ic_kinds = fn (ty: int) ->"
puts "  match ty with"
nodes.each_with_index do |node, i|
  ks = (node["fields"] || []).map { |f| KINDS[f.fetch("type")] or abort "gen_ic_schema: #{node["name"]}.#{f["name"]}: #{f["type"]}" }.join
  puts "  | #{i + 1} -> \"#{node["name"] == "DefNode" ? "!" : ""}#{ks}\""
end
puts "  | _ -> \"\";"
puts ""
puts "let ic_type_name = fn (ty: int) ->"
puts "  match ty with"
nodes.each_with_index { |node, i| puts "  | #{i + 1} -> \"#{node["name"]}\"" }
puts "  | _ -> \"?\";"
puts ""
nodes.each_with_index do |node, i|
  s = short.(node.fetch("name"))
  puts "let pt_#{s} = fn (u: unit) -> #{i + 1};"
end
puts ""
nodes.each do |node|
  s = short.(node.fetch("name"))
  (node["fields"] || []).each_with_index do |f, k|
    puts "let pn_#{s}_#{f.fetch("name")} = fn cx -> fn (n: int) -> ic_fa cx n #{k};"
    kind = KINDS[f.fetch("type")]
    puts "let pn_#{s}_#{f.fetch("name")}_b = fn cx -> fn (n: int) -> ic_fb cx n #{k};" if %w[L K l o i].include?(kind)
  end
  next unless node["flags"]
  flags.fetch(node["flags"]).each_with_index do |v, k|
    puts "let pq_#{s}_#{v.downcase} = fn cx -> fn (n: int) -> bit_and (ic_flags cx n) #{4 << k} != 0;"
  end
end
