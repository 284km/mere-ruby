# Embed the syntax_suggest 2.0.3 sources shipped with clean Ruby 4.0.10.
# Source tools/ref_ruby.sh before running this generator. No gem installation
# is needed. Keep the upstream source and license notices unchanged.
require 'rbconfig'
root = ARGV.fetch(0, RbConfig::CONFIG.fetch('rubylibdir'))
files = [File.join(root, 'syntax_suggest.rb')] + Dir[File.join(root, 'syntax_suggest/**/*.rb')].sort
# The standalone SyntaxSuggest API requires OptionParser via its CLI.
# These pure-Ruby dependencies are fallbacks after every actual load-path file.
files += ['optparse.rb', 'optparse/version.rb'].map { |name| File.join(root, name) }
abort 'syntax_suggest source tree is missing' unless files.size > 1

def lit(line)
  line.gsub(/[\\"{}\t\r]/) { |c| { "\\" => "\\\\", '"' => '\\"', "{" => "\\{", "}" => "\\}", "\t" => "\\t", "\r" => "\\r" }.fetch(c) }
end
puts '// GENERATED by tools/gen_syntax_suggest_lib.rb from Ruby 4.0.10'
puts '// syntax_suggest 2.0.3 (MIT license; lib/syntax_suggest.LICENSE.txt), plus'
puts '// its unchanged OptionParser dependency (Ruby/BSD-2-Clause license). Do not edit.'
puts 'let syntax_suggest_lib_src = fn (name: str) ->'
puts '  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in'
files.each_with_index do |file, i|
  feature = file.delete_prefix(root + '/').delete_suffix('.rb')
  puts "  #{i.zero? ? 'if' : 'else if'} str_eq n \"#{feature}\" then"
  File.read(file).lines.each_with_index do |line, j|
    puts "    #{j.zero? ? '' : '++ '}\"#{lit(line.chomp)}#{line.end_with?("\n") ? '\\n' : ''}\""
  end
end
puts '  else "";'
