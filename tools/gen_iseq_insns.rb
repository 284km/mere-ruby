# Generates lib/iseq_insns_ext.rb: the YARV instruction table ruby 4.0.9
# defines -- each instruction's operand types, in order, from insns.def --
# and the operand-unified instructions opt_operand.def makes (getlocal_WC_0,
# putobject_INT2FIX_1_, ...). The ISeq compiler (lib/iseq_compiler_ext.rb)
# lays its instructions out by these lengths, and to_a / disasm print them.
#
#   ruby tools/gen_iseq_insns.rb RUBY_SRC > lib/iseq_insns_ext.rb
src = ARGV[0] or abort "usage: gen_iseq_insns.rb RUBY_SRC"
insns = []
File.read(File.join(src, "insns.def")).scan(/^DEFINE_INSN\n(\w+)\n\(([^)]*)\)/) do |name, ops|
  types = ops.split(",").map { |o| o.strip.split(/\s+/)[0...-1].join(" ") }.reject(&:empty?)
  insns << [name, types]
end
unified = []
File.read(File.join(src, "defs/opt_operand.def")).split("__END__").first.each_line do |l|
  next if l.start_with?("#") || l.strip.empty?
  name, rest = l.strip.split(/\s+/, 2)
  args = rest.split(",").map(&:strip)
  unified << [name, args]
end
puts "# frozen_string_literal: true"
puts "# GENERATED by tools/gen_iseq_insns.rb from ruby 4.0.9's insns.def and"
puts "# defs/opt_operand.def -- do not edit."
puts "class RubyVM::InstructionSequence"
puts "  INSN_OPERANDS__ = {"
insns.each { |n, t| puts "    #{n}: #{t.inspect}," }
puts "  }.freeze"
puts "  # [instruction, operands it fixes] -> the unified instruction"
puts "  INSN_UNIFIED__ = ["
unified.each { |n, a| puts "    [:#{n}, #{a.inspect}]," }
puts "  ].freeze"
puts "end"
