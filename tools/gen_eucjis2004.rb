# Generates m_eucjis2004.mere: where EUC-JIS-2004 (JIS X 0213) reads
# otherwise than EUC-JP, ruby's own transcoder being the oracle (as for
# gen_jis0208.rb and gen_dbcs_tables.rb).
#
#   ruby tools/gen_eucjis2004.rb > m_eucjis2004.mere
#
# Every two-byte code (A1A1-FEFE) and three-byte one (8FA1A1-8FFEFE) is read
# both ways; one that differs is written "CODE=CP" (hex), and "CODE=-" for a
# code EUC-JP reads that EUC-JIS-2004 does not. The encoder writes a
# character found here at its code first, and refuses EUC-JP's bytes for one
# when they are a "-" here.
def read(bytes, enc)
  bytes.dup.force_encoding(enc).encode("UTF-8")
rescue Encoding::UndefinedConversionError, Encoding::InvalidByteSequenceError
  nil
end
out = []
codes = []
(0xA1..0xFE).each { |l| (0xA1..0xFE).each { |t| codes << [l, t] } }
(0xA1..0xFE).each { |l| (0xA1..0xFE).each { |t| codes << [0x8F, l, t] } }
codes.each do |c|
  b = c.pack("C*")
  a = read(b, "EUC-JIS-2004")
  e = read(b, "EUC-JP")
  next if a == e
  raise "multi-codepoint #{c.inspect}" if a && a.size > 1
  out << c.map { |x| format("%02X", x) }.join + "=" + (a ? format("%X", a.ord) : "-")
end
puts "// GENERATED by tools/gen_eucjis2004.rb from ruby #{RUBY_VERSION} -- do not edit."
puts "// Where EUC-JIS-2004 reads otherwise than EUC-JP (#{out.size} codes):"
puts "// \"CODE=CP\" in hex, \"CODE=-\" for a code only EUC-JP reads."
puts ""
puts "let ej2004_src = \"#{out.join(",")}\";"
