# Generates m_emoji.mere: the carrier emoji of the DoCoMo, KDDI and SoftBank
# encodings (UTF8-*, SJIS-*, ISO-2022-JP-KDDI), as overlays on the
# encodings they are built on, and the exchange table between the carriers
# and Unicode. Run under the reference ruby, which is the oracle:
#
#   ~/.rbenv/versions/4.0.9/bin/ruby tools/gen_emoji_tables.rb RUBY_SRC > m_emoji.mere
#
# RUBY_SRC is a ruby source tree (enc/trans/emoji-exchange-tbl.rb, the
# exchange table, is read as data). The SJIS and ISO-2022-JP overlays are
# measured: every two-byte code is decoded through the carrier encoding and
# through its base (Windows-31J, ISO-2022-JP), and every BMP character
# encoded both ways; only the differences are kept.
src = ARGV[0] or abort "usage: gen_emoji_tables.rb RUBY_SRC"
load File.join(src, "enc/trans/emoji-exchange-tbl.rb")

CARRIERS = %w[DoCoMo KDDI SoftBank]
cp_of = ->(hex) { [hex].pack("H*").force_encoding("UTF-8").ord }

out = []
put = ->(name, pairs) { out << [name, pairs.map { |k, v| "#{k}:#{v}" }.join(";")] }

# the exchange: company -> company, a code point to a code point, or -1
# (:undef, no equivalent: Encoding::UndefinedConversionError)
names = { "UTF-8" => "Unicode" }
CARRIERS.each { |c| names["UTF8-#{c}"] = c }
EMOJI_EXCHANGE_TBL.each do |from, tos|
  tos.each do |to, list|
    pairs = list.map { |a, b| [cp_of.(a), b == :undef ? -1 : cp_of.(b)] }
    put.("x_#{names[from]}_#{names[to]}", pairs)
  end
end

def try
  yield
rescue EncodingError
  nil
end

CARRIERS.each do |c|
  dec = []
  (0x81..0xFC).each do |l|
    (0x40..0xFC).each do |t|
      next if t == 0x7F
      s = [l, t].pack("C*")
      r = try { s.dup.force_encoding("SJIS-#{c}").encode("UTF8-#{c}") }
      b = try { s.dup.force_encoding("Windows-31J").encode("UTF-8") }
      next if r == (b && b.dup.force_encoding("UTF8-#{c}"))
      dec << [l * 256 + t, r ? r.dup.force_encoding("UTF-8").ord : -1]
    end
  end
  put.("sd_#{c}", dec)
  enc = []
  (0x80..0xFFFF).each do |cp|
    next if cp.between?(0xD800, 0xDFFF)
    u = [cp].pack("U")
    r = try { u.dup.force_encoding("UTF8-#{c}").encode("SJIS-#{c}") }
    b = try { u.encode("Windows-31J") }
    next if r && b && r.b == b.b
    next if r.nil? && b.nil?
    enc << [cp, r ? r.b.unpack1("n") : -1]
  end
  put.("se_#{c}", enc)
end

# ISO-2022-JP-KDDI: a JIS X 0208 pair read differently from ISO-2022-JP's
dec = []
(0x21..0x7E).each do |a|
  (0x21..0x7E).each do |b|
    s = "\e$B" + [a, b].pack("C*") + "\e(B"
    r = try { s.dup.force_encoding("ISO-2022-JP-KDDI").encode("UTF8-KDDI") }
    q = try { s.dup.force_encoding("ISO-2022-JP").encode("UTF-8") }
    next if r == (q && q.dup.force_encoding("UTF8-KDDI"))
    dec << [a * 256 + b, r ? r.dup.force_encoding("UTF-8").ord : -1]
  end
end
put.("jd_KDDI", dec)
enc = []
(0x80..0xFFFF).each do |cp|
  next if cp.between?(0xD800, 0xDFFF)
  u = [cp].pack("U")
  r = try { u.dup.force_encoding("UTF8-KDDI").encode("ISO-2022-JP-KDDI") }
  q = try { u.encode("ISO-2022-JP") }
  next if r == (q && q.dup.force_encoding("ISO-2022-JP-KDDI"))
  next if r.nil? && q.nil?
  code = r && r.b =~ /\e\$B(..)\e\(B/n ? $1.unpack1("n") : -1
  enc << [cp, code]
end
put.("je_KDDI", enc)

puts "// GENERATED by tools/gen_emoji_tables.rb from ruby 4.0.9 (the exchange"
puts "// table enc/trans/emoji-exchange-tbl.rb, and the SJIS / ISO-2022-JP"
puts "// carrier overlays measured against it) -- do not edit."
puts "//"
puts "// x_A_B: a code point of company A as company B's (-1: none, :undef)"
puts "// sd_C / se_C: a Shift_JIS code read / written by SJIS-C where"
puts "//   Windows-31J's differs (-1: undefined there)"
puts "// jd_KDDI / je_KDDI: the same for ISO-2022-JP-KDDI's JIS X 0208 pairs"
puts ""
puts "let emoji_tables = map_new ();"
puts "let emoji_src = fn (name: str) ->"
out.each_with_index do |(name, body), i|
  puts "  #{i == 0 ? "if" : "else if"} str_eq name #{name.inspect} then"
  chunks = body.scan(/.{1,4000}(?:;|\z)/)
  chunks = [""] if chunks.empty?
  chunks.each_with_index do |chunk, j|
    puts "    #{j == 0 ? "" : "++ "}#{chunk.inspect}"
  end
end
puts "  else \"\";"
