# Generates m_internal_ruby.mere: the builtin methods the reference ruby
# writes in Ruby itself (source_location in "<internal:...>": Integer#times,
# Kernel#tap, Array#first...). TracePoint reports those as :call / :return
# with that path, and every other builtin as :c_call / :c_return -- so the
# kind of event a builtin call makes is this list's to say (note 435).
#
#   . ./tools/ref_ruby.sh && ruby --disable-gems tools/gen_internal_ruby.rb > m_internal_ruby.mere
#
# One entry per method, "Owner#name" (or "Owner.name" for a singleton one),
# with its path and first line: `Integer#times<TAB><internal:numeric><TAB>254`.
SKIP = /\A(Gem|DidYouMean|ErrorHighlight|SyntaxSuggest|Bundler|RubyVM|Ractor|Monitor|MonitorMixin)\b/
rows = []
ObjectSpace.each_object(Module) do |m|
  n = (m.name rescue nil)
  next unless n && n !~ /\A#/ && n !~ SKIP
  (m.instance_methods(false) + m.private_instance_methods(false) + m.protected_instance_methods(false)).uniq.each do |x|
    loc = (m.instance_method(x).source_location rescue nil)
    rows << "#{n}##{x}\t#{loc[0]}\t#{loc[1]}" if loc && loc[0].start_with?("<internal:")
  end
  m.singleton_methods(false).each do |x|
    loc = (m.method(x).source_location rescue nil)
    rows << "#{n}.#{x}\t#{loc[0]}\t#{loc[1]}" if loc && loc[0].start_with?("<internal:")
  end
end
rows = rows.uniq.sort
puts "// GENERATED by tools/gen_internal_ruby.rb from ruby #{RUBY_VERSION} -- do not edit."
puts "// The builtins ruby writes in Ruby (\"<internal:...>\"): TracePoint reports"
puts "// them as :call / :return, every other builtin as :c_call / :c_return."
puts "// One row per method: Owner#name (Owner.name for a singleton one), path, line."
puts "let internal_ruby_rows ="
rows.each_with_index do |r, i|
  puts "  \"#{r.gsub("\\", "\\\\\\\\").gsub('"', '\\"').gsub("\t", "\\t")}\\n\"#{i == rows.size - 1 ? ";" : " ++"}"
end
