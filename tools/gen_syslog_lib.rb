# Generates m_syslog_lib.mere: the syslog library as mere-ruby ships it,
# turned into Mere string literals so that `require "syslog"` needs no gem on
# the load path.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_syslog_lib.rb > m_syslog_lib.mere
#
# Two halves, as in the gem:
#
# - The Ruby half: syslog 0.3.0's lib/ (syslog.rb and syslog/logger.rb), byte
#   for byte. They are distributed under Ruby's license (the gemspec:
#   `s.licenses = ["Ruby", "BSD-2-Clause"]`).
# - The C half: ext/syslog/syslog.c is a C extension mere-ruby cannot load.
#   Its replacement is lib/syslog_ext.rb in this repository, written by hand
#   in Ruby, and answered under the name the gem requires it by, "syslog_ext".
#
# The gem directory is found from the reference ruby unless given.
gem_dir = ARGV[0] || Gem::Specification.find_by_name("syslog").gem_dir
lib = "#{gem_dir}/lib"
here = File.expand_path("..", __dir__)
files = [["syslog_ext", "#{here}/lib/syslog_ext.rb"]]
%w[syslog syslog/logger].each { |n| files << [n, "#{lib}/#{n}.rb"] }

def lit(line)
  line.gsub(/[\\"{}\t\r]/) { |c| { "\\" => "\\\\", '"' => '\\"', "{" => "\\{", "}" => "\\}", "\t" => "\\t", "\r" => "\\r" }[c] }
end

version = File.basename(gem_dir)[/\d[\d.]*\z/]
puts "// GENERATED by tools/gen_syslog_lib.rb from syslog #{version}'s lib/"
puts "// and lib/syslog_ext.rb -- do not edit. Answered by syslog_lib_src,"
puts "// which do_require asks after bigdecimal_lib_src."
puts ""
puts "let syslog_lib_src = fn (name: str) ->"
puts "  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in"
files.each_with_index do |(n, path), i|
  src = File.read(path)
  puts "  #{i == 0 ? "if" : "else if"} str_eq n \"#{n}\" then"
  lines = src.lines
  lines.each_with_index do |l, j|
    body = l.chomp
    nl = l.end_with?("\n") ? "\\n" : ""
    puts "    \"#{lit(body)}#{nl}\"#{j == lines.size - 1 ? "" : " ++"}"
  end
end
puts "  else \"\";"
