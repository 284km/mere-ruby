# Generates m_pathname_lib.mere: lib/pathname_ext.rb -- Pathname as mere-ruby
# ships it -- and lib/find_ext.rb (Find, which Pathname#find requires) and
# lib/fileutils_ext.rb (FileUtils, which Pathname#rmtree requires), turned
# into Mere string literals so that `require "pathname"` (and "pathname.so"),
# `require "find"` and `require "fileutils"` need no file on the load path;
# lib/stringio_ext.rb, lib/strscan_ext.rb and lib/tmpdir_ext.rb (ruby's own
# lib/tmpdir.rb) ride along.
#
#   ruby tools/gen_pathname_lib.rb > m_pathname_lib.mere
#
# Ruby 4.0 has Pathname in its core (pathname.c). lib/pathname_ext.rb is the
# Ruby half of ruby 3.4's lib/pathname.rb (Tanaka Akira, Ruby's license) --
# cleanpath, plus, relative_path_from, descend and the rest, byte for byte
# where it can be -- over a C half written in Ruby, each method a delegation
# to File / Dir / IO (see the file).
here = File.expand_path("..", __dir__)
files = [[%w[pathname pathname.so], File.read("#{here}/lib/pathname_ext.rb")],
         [%w[find], File.read("#{here}/lib/find_ext.rb")],
         [%w[fileutils], File.read("#{here}/lib/fileutils_ext.rb")],
         [%w[stringio stringio.so], File.read("#{here}/lib/stringio_ext.rb")],
         [%w[strscan strscan.so], File.read("#{here}/lib/strscan_ext.rb")],
         [%w[tmpdir], File.read("#{here}/lib/tmpdir_ext.rb")],
         [%w[cgi/escape], File.read("#{here}/lib/cgi_escape_ext.rb")],
         [%w[cgi cgi/util], File.read("#{here}/lib/cgi_ext.rb")],
         # (the ports' magic comments are dropped: in the middle of a file
         #  ruby warns that they are ignored, and assert_separately sees it)
         [%w[date date_core], File.read("#{here}/lib/date_ext.rb") +
           "class Date\n" + File.read("#{here}/lib/date_parse_ext.rb").sub(/\A# frozen_string_literal: \w+\n/, "") + "\n" +
           File.read("#{here}/lib/date_strptime_ext.rb").sub(/\A# frozen_string_literal: \w+\n/, "") +
           "\n  private_constant :MereDateParse, :MereDateStrptime\nend\n"],
         [%w[time], File.read("#{here}/lib/time_ext.rb")],
         [%w[tempfile], File.read("#{here}/lib/tempfile_ext.rb")],
         [%w[socket socket.so], File.read("#{here}/lib/socket_ext.rb")],
         [%w[forwardable], File.read("#{here}/lib/forwardable_ext.rb")],
         [%w[shellwords], File.read("#{here}/lib/shellwords_ext.rb")],
         [%w[singleton], File.read("#{here}/lib/singleton_ext.rb")],
         [%w[logger], File.read("#{here}/lib/logger_ext.rb")],
         [%w[pp], File.read("#{here}/lib/pp_ext.rb")],
         [%w[prettyprint], File.read("#{here}/lib/prettyprint_ext.rb")],
         [%w[io/console io/console.so], File.read("#{here}/lib/io_console_ext.rb")],
         [%w[io/console/size], File.read("#{here}/lib/io_console_size_ext.rb")],
         [%w[pty pty.so], File.read("#{here}/lib/pty_ext.rb")],
         [%w[expect], File.read("#{here}/lib/expect_ext.rb")]]

def lit(line)
  line.gsub(/[\\"{}\t\r]/) { |c| { "\\" => "\\\\", '"' => '\\"', "{" => "\\{", "}" => "\\}", "\t" => "\\t", "\r" => "\\r" }[c] }
end

puts "// GENERATED by tools/gen_pathname_lib.rb from lib/pathname_ext.rb -- do not"
puts "// edit. Answered by pathname_lib_src, which do_require asks after"
puts "// prism_lib_src."
puts ""
puts "let pathname_lib_src = fn (name: str) ->"
puts "  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in"
files.each_with_index do |(names, src), i|
  cond = names.map { |n| "str_eq n \"#{n}\"" }.join(" || ")
  puts "  #{i == 0 ? "if" : "else if"} #{cond} then"
  src.lines.each_with_index do |l, j|
    body = l.chomp
    nl = l.end_with?("\n") ? "\\n" : ""
    sep = j == 0 ? "    " : "    ++ "
    puts "#{sep}\"#{lit(body)}#{nl}\""
  end
end
puts "  else \"\";"
