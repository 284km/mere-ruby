# ruby tools/gen_openssl_lib.rb > m_openssl_lib.mere
require 'pathname'
root = Pathname.new(__dir__).parent
names = %w[core bn oid asn1 backend]
source = names.map { |name| root.join("lib/openssl_#{name}.rb").read }.join("\n")
if ARGV.include?('--ruby')
  print source
  exit
end
puts '// GENERATED by tools/gen_openssl_lib.rb.'
puts 'let openssl_lib_source = fn (u: unit) ->'
lines = source.lines
lines.each_with_index do |line, i|
  body = line.chomp.gsub(/[\\"{}\t\r]/) do |c|
    {"\\" => "\\\\", '"' => '\\"', '{' => '\\{', '}' => '\\}', "\t" => '\\t', "\r" => '\\r'}[c]
  end
  puts "  \"#{body}#{line.end_with?("\n") ? '\\n' : ''}\"#{i + 1 == lines.size ? ';' : ' ++'}"
end
