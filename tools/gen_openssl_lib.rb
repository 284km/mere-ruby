# ruby tools/gen_openssl_lib.rb > m_openssl_lib.mere
require 'pathname'
root = Pathname.new(__dir__).parent
names = %w[core bn oid asn1 backend primitives native_cipher pkey ec config x509 pkcs12 pkcs7]
source = names.map { |name| root.join("lib/openssl_#{name}.rb").read }.join("\n")
source = root.join('vendor/openssl/BSDL').read.lines.map { |line| '# ' + line }.join + source
%w[cipher marshal pkey x509].each do |name|
  source << "\n" << root.join("vendor/openssl/lib/openssl/#{name}.rb").read.lines.reject { |line| line.start_with?('require_relative ', '# frozen_string_literal:') }.join
end
source << "\nif OpenSSL.__native_available\n" << root.join('lib/openssl_ssl.rb').read
%w[buffering ssl].each do |name|
  source << "\n" << root.join("vendor/openssl/lib/openssl/#{name}.rb").read.lines.reject { |line| line.start_with?('require ', '# frozen_string_literal:') }.join
end
source << "\nelse\nmodule OpenSSL::SSL\nclass SSLContext\ndef self.new(*)\nraise NotImplementedError, 'native OpenSSL provider is unavailable on this target'\nend\nend\nend\nend\n"
source = root.join('vendor/openssl/lib/ipaddr.rb').read if ARGV.include?('--ipaddr')
if ARGV.include?('--ruby')
  print source
  exit
end
puts '// GENERATED by tools/gen_openssl_lib.rb.'
puts "let #{ARGV.include?('--ipaddr') ? 'ipaddr' : 'openssl'}_lib_source = fn (u: unit) ->"
lines = source.lines
lines.each_with_index do |line, i|
  body = line.chomp.gsub(/[\\"{}\t\r]/) do |c|
    {"\\" => "\\\\", '"' => '\\"', '{' => '\\{', '}' => '\\}', "\t" => '\\t', "\r" => '\\r'}[c]
  end
  puts "  \"#{body}#{line.end_with?("\n") ? '\\n' : ''}\"#{i + 1 == lines.size ? ';' : ' ++'}"
end
