# Generates m_internal_disasm.mere: RubyVM::InstructionSequence#disasm of the
# builtins the reference ruby writes in Ruby (the rows of m_internal_ruby.mere),
# as that ruby prints them. RubyVM::InstructionSequence.of(method) answers
# these for such a builtin -- `"".method(:unpack)` is <internal:pack>'s
# `opt_invokebuiltin_delegate_leave` -- since there is no YARV here to read.
#
#   . ./tools/ref_ruby.sh && ruby --disable-gems tools/gen_internal_disasm.rb > m_internal_disasm.mere
#
# One entry per method, "Owner#name" (or "Owner.name"), then chr 1, the
# disassembly, chr 2.
SKIP = /\A(Gem|DidYouMean|ErrorHighlight|SyntaxSuggest|Bundler|RubyVM|Ractor|Monitor|MonitorMixin)\b/
rows = {}
ObjectSpace.each_object(Module) do |m|
  n = (m.name rescue nil)
  next unless n && n !~ /\A#/ && n !~ SKIP
  (m.instance_methods(false) + m.private_instance_methods(false) + m.protected_instance_methods(false)).uniq.each do |x|
    um = (m.instance_method(x) rescue nil)
    loc = (um.source_location rescue nil)
    next unless loc && loc[0].start_with?("<internal:")
    d = (RubyVM::InstructionSequence.of(um).disasm rescue nil)
    rows["#{n}##{x}"] = d if d
  end
  m.singleton_methods(false).each do |x|
    mm = (m.method(x) rescue nil)
    loc = (mm.source_location rescue nil)
    next unless loc && loc[0].start_with?("<internal:")
    d = (RubyVM::InstructionSequence.of(mm).disasm rescue nil)
    rows["#{n}.#{x}"] = d if d
  end
end
esc = ->(s) { s.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }.gsub("{") { "\\{" }.gsub("\n") { "\\n" } }
puts "// GENERATED by tools/gen_internal_disasm.rb from ruby #{RUBY_VERSION} -- do not edit."
puts "// RubyVM::InstructionSequence#disasm of the builtins ruby writes in Ruby:"
puts "// \"Owner#name\" chr 1 the disassembly chr 2, one after another."
puts "// Build once without retaining every concatenated prefix at startup."
puts "let internal_disasm_text = region DISASM {"
puts "  let b = strbuf_new () in"
rows.keys.sort.each do |k|
  puts "  let _ = strbuf_push b \"#{esc[k]}\" in"
  puts "  let _ = strbuf_push b (chr 1) in"
  puts "  let _ = strbuf_push b \"#{esc[rows[k]]}\" in"
  puts "  let _ = strbuf_push b (chr 2) in"
end
puts "  strbuf_to_str b"
puts "};"
