# Generates m_bigdecimal_lib.mere: the bigdecimal library as mere-ruby ships
# it, turned into Mere string literals so that `require "bigdecimal"` needs no
# gem on the load path.
#
#   . ./tools/ref_ruby.sh && ruby tools/gen_bigdecimal_lib.rb > m_bigdecimal_lib.mere
#
# Two halves, as in the gem:
#
# - The Ruby half: bigdecimal 4.0.1's lib/ (bigdecimal.rb, bigdecimal/util.rb,
#   bigdecimal/math.rb, bigdecimal/jacobian.rb, bigdecimal/ludcmp.rb,
#   bigdecimal/newton.rb), byte for byte, so a line number in a backtrace
#   names the line the reference's copy has there. They are distributed under
#   Ruby's license (the gemspec: `s.licenses = ["Ruby", "BSD-2-Clause"]`).
# - The C half: ext/bigdecimal/bigdecimal.c is a C extension mere-ruby cannot
#   load. Its replacement is lib/bigdecimal_so.rb in this repository, written
#   by hand in Ruby, and answered under the name the gem requires it by,
#   "bigdecimal.so".
#
# The gem directory is found from the reference ruby unless given.
gem_dir = ARGV[0] || Gem::Specification.find_by_name("bigdecimal").gem_dir
lib = "#{gem_dir}/lib"
here = File.expand_path("..", __dir__)
files = [["bigdecimal.so", "#{here}/lib/bigdecimal_so.rb"]]
%w[bigdecimal bigdecimal/util bigdecimal/math bigdecimal/jacobian bigdecimal/ludcmp bigdecimal/newton].each do |n|
  files << [n, "#{lib}/#{n}.rb"]
end

def lit(line)
  line.gsub(/[\\"{}\t\r]/) { |c| { "\\" => "\\\\", '"' => '\\"', "{" => "\\{", "}" => "\\}", "\t" => "\\t", "\r" => "\\r" }[c] }
end

version = File.basename(gem_dir)[/\d[\d.]*\z/]
puts "// GENERATED by tools/gen_bigdecimal_lib.rb from bigdecimal #{version}'s lib/"
puts "// and lib/bigdecimal_so.rb -- do not edit. Answered by bigdecimal_lib_src,"
puts "// which do_require asks after json_lib_src."
puts ""
puts "let bigdecimal_lib_src = fn (name: str) ->"
puts "  let n = (if ends_with_rb name then substring name 0 (str_len name - 3) else name) in"
files.each_with_index do |(n, path), i|
  src = File.read(path)
  puts "  #{i == 0 ? "if" : "else if"} str_eq n \"#{n}\" then"
  lines = src.lines
  lines.each_with_index do |l, j|
    body = l.chomp
    nl = l.end_with?("\n") ? "\\n" : ""
    puts "    \"#{lit(body)}#{nl}\"#{j == lines.size - 1 ? "" : " ++"}"
  end
end
puts "  else \"\";"
