"""Build inputs the native CLI and the embedding probes share: the OpenSSL
provider selection, and the C sources of the native extension boundary."""
from pathlib import Path
import os
import platform
import shlex
import shutil
import subprocess


def openssl_flags():
    prefix = os.environ.get('OPENSSL_PREFIX', '')
    if not prefix and platform.system() == 'Darwin' and shutil.which('brew'):
        prefix = subprocess.check_output(['brew', '--prefix', 'openssl@3'], text=True).strip()
    if prefix:
        root = Path(prefix).resolve()
        if not (root / 'include/openssl/ssl.h').is_file():
            raise SystemExit('OPENSSL_PREFIX has no OpenSSL headers')
        return (['-I' + str(root / 'include')],
                ['-L' + str(root / 'lib'), '-Wl,-rpath,' + str(root / 'lib'),
                 '-lssl', '-lcrypto'])
    if shutil.which('pkg-config') and subprocess.run(
            ['pkg-config', '--exists', 'openssl >= 3.0'], check=False).returncode == 0:
        return tuple(shlex.split(subprocess.check_output(
            ['pkg-config', option, 'openssl'], text=True))
                     for option in ['--cflags', '--libs'])
    return [], ['-lssl', '-lcrypto']


ROOT = Path(__file__).resolve().parents[2]
BRIDGE = Path(__file__).resolve().parent


def native_bridge_sources(compiler=None):
    """The C side of the interpreter's native extension externs. Every link of
    the emitted interpreter needs them, as tools/build.sh lists them. Their
    two headers are generated by the compiler that emits the interpreter;
    without one, the headers an earlier build wrote must be there."""
    for name in ['reentry', 'exception_api']:
        target = BRIDGE / (name + '.h')
        if compiler is None:
            if not target.is_file():
                raise SystemExit(f'{target} is missing: build the interpreter first')
            continue
        header = subprocess.check_output(
            [str(compiler), '--ffi-header', str(BRIDGE / (name + '.mere'))], cwd=ROOT)
        target.write_bytes(header)
    return [BRIDGE / (name + '.c') for name in
            ['bridge', 'reentry', 'handle_slots', 'exception_bridge', 'typed_bridge']]
