"""Build inputs the native CLI and the embedding probes share: the OpenSSL
provider selection, and the C sources of the native extension boundary."""
from pathlib import Path
import os
import platform
import shlex
import shutil
import subprocess


def openssl_flags():
    prefix = os.environ.get('OPENSSL_PREFIX', '')
    if not prefix and platform.system() == 'Darwin' and shutil.which('brew'):
        prefix = subprocess.check_output(['brew', '--prefix', 'openssl@3'], text=True).strip()
    if prefix:
        root = Path(prefix).resolve()
        if not (root / 'include/openssl/ssl.h').is_file():
            raise SystemExit('OPENSSL_PREFIX has no OpenSSL headers')
        return (['-I' + str(root / 'include')],
                ['-L' + str(root / 'lib'), '-Wl,-rpath,' + str(root / 'lib'),
                 '-lssl', '-lcrypto'])
    if shutil.which('pkg-config') and subprocess.run(
            ['pkg-config', '--exists', 'openssl >= 3.0'], check=False).returncode == 0:
        return tuple(shlex.split(subprocess.check_output(
            ['pkg-config', option, 'openssl'], text=True))
                     for option in ['--cflags', '--libs'])
    return [], ['-lssl', '-lcrypto']


ROOT = Path(__file__).resolve().parents[2]
CAPI = ROOT / 'capi'

# What compiling the C API's sources needs, as tools/build.sh passes it.
NATIVE_CFLAGS = ['-DMR_CAPI_BUILD', '-I', str(CAPI / 'include'), '-I', str(CAPI), '-I', str(CAPI / 'vendor'),
                 '-I', str(CAPI / 'standin')]


def native_bridge_sources(compiler=None):
    """The C side of Ruby's C API (capi/*.c). Every link of the emitted
    interpreter needs it, as tools/build.sh lists it, compiled with
    NATIVE_CFLAGS. Its interface header is generated by the compiler that
    emits the interpreter; without one, the header an earlier build wrote
    must be there."""
    header = CAPI / 'mere_capi.h'
    if compiler is None:
        if not header.is_file():
            raise SystemExit(f'{header} is missing: build the interpreter first')
    else:
        header.write_bytes(subprocess.check_output(
            [str(compiler), '--ffi-header', str(ROOT / 'm_capi_api.mere')], cwd=ROOT))
    return sorted(CAPI.glob('*.c'))
